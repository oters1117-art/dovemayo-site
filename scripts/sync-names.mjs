// Copies the random name generator (X:/AI/이름생성기) into dist/name/, and its Spore-style word lists
// into worker/spore-names.mjs (the showcase board picks nicknames from them).
// Usage: node scripts/sync-names.mjs [path to the generator]
import {copyFileSync,mkdirSync,existsSync,readFileSync,writeFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const src=process.argv[2]||'X:/AI/이름생성기';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const dest=join(root,'dist','name');
if(!existsSync(join(src,'index.html'))){console.error('name generator not found at '+src);process.exit(1);}
mkdirSync(dest,{recursive:true});
const files=['index.html','names-data.js','spore-data.js'];
for(const f of files)copyFileSync(join(src,f),join(dest,f));
const m=/window\.SPORE_DATA=(\{[\s\S]*\});/.exec(readFileSync(join(src,'spore-data.js'),'utf8'));
if(!m){console.error('spore-data.js: SPORE_DATA not found');process.exit(1);}
const d=JSON.parse(m[1]);
writeFileSync(join(root,'worker','spore-names.mjs'),'// Generated by scripts/sync-names.mjs from X:/AI/이름생성기/spore-data.js (do not edit)\nexport const ADJ='+JSON.stringify(d.adj)+';\nexport const NOUN='+JSON.stringify(d.noun)+';\n');
console.log('name: '+files.length+' files -> dist/name/, spore words '+d.adj.length+'+'+d.noun.length+' -> worker/spore-names.mjs');
